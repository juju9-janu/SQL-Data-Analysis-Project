-- 1.Show the total amount of male patients and the total amount of female patients in the patients table.
-- Display the two results in the same row.
select (SELECT count(*) from patients where gender ='Male') as male_count,(select count(*) from patients where gender ='Female') as female_count;
-- 2. Patient Distribution by City
-- Identify the top 5 cities with the highest number of registered patients.
select city from patients group by city order by city desc limit 5;
-- 3.Department Performance
-- Find the total number of appointments and total consultation revenue generated by each department.
select 
sum(consultation_fee) as total_consultation_revenue,
department, count(*) as total_appointments 
from appointments 
group by appointment_id;
-- 4. Doctor Workload Analysis
-- Find the number of appointments handled by each doctor and rank doctors by appointment count.
select doctor_name,count(*) as appointments_handeled ,
 Dense_rank() over(order by count(*) desc) as rank_of_doctors 
 from appointments group by doctor_name ;
-- 5. Revenue by Doctor
-- Calculate each doctor's total consultation revenue and average consultation fee. Identify the top 5 doctors by revenue.
select doctor_name,sum(consultation_fee) as total_consultation_revenue ,
avg(consultation_fee) as average_consultation_revenue  
from appointments 
group by doctor_name 
order by total_consultation_revenue  desc limit 5;
-- 6.Patients Without Appointments
-- Find all registered patients who do not have an appointment record.
select patients.patient_id,appointments.appointment_id 
from patients left join appointments on patients.patient_id=appointments.patient_id 
where appointment_id is null;
-- 7.Appointment Revenue by Month
-- Calculate monthly appointment counts and consultation revenue, ordered chronologically.
select year(appointment_date),month(appointment_date),count(*),sum(consultation_fee) 
from appointments 
group by appointment_date,consultation_fee 
order by year(appointment_date),month(appointment_date) asc ;

-- 8.Department Fee Comparison
-- Find the department with the highest and lowest average consultation fee, along with appointment volume.
select department, avg(consultation_fee) as avg_fee from appointments group by department  order by avg_fee desc ;
-- 9. First and Latest Appointment
-- For each patient with an appointment, identify their earliest and latest appointment date
select patients.patient_id,max(appointments.appointment_date) as max_appointment,
min(appointments.appointment_id) as min_appointment 
from patients join appointments on patients.patient_id=appointments.patient_id 
group by patients.patient_id;

-- 10. Rank Departments by Revenue
-- Rank departments from highest to lowest revenue and identify departments tied at the same rank.
with department_r as (
select department,sum(consultation_fee) as total_revenue 
from appointments 
group by department )
select department , total_revenue, dense_rank() over(order by total_revenue desc) as revenue_rank from department_r;

-- 11.Data Quality Check
-- Question: Identify appointments whose patient_id does not exist in the patients table, and check for missing patient IDs or consultation fees.
select appointments.patient_id,patients.patient_id from appointments 
left join patients on appointments.patient_id=patients.patient_id  
where patients.patient_id is null;

-- 12. Top Departments by Month
-- Question: Rank departments by total consultation revenue for each month and display the highest-revenue department for every month.

with department_r as (
select 
department,sum(consultation_fee) as total_revenue,
     month(appointment_date) as months
from appointments 
group by department,month(appointment_date) )
select department ,months, total_revenue, rank() over(partition by months order by total_revenue desc) as revenue_rank from department_r ;

-- 13. Above-Average Consultation Fees
-- Question: Find all appointments where the consultation fee is greater than the average consultation fee across all appointments.
select * from appointments where consultation_fee >(select avg(consultation_fee) from appointments);
-- 14. Department Revenue Contribution
-- Question: Calculate the percentage of total consultation revenue contributed by each department.
select department,sum(consultation_fee) as total_fee,sum(consultation_fee)*100.0/(select sum(consultation_fee ) 
from appointments) as percentation_consultation_fee from appointments group by department;
-- 15. Age Group Analysis
-- Question: Categorize patients into age groups: under 18, 18–30, 31–45, 46–60, and over 60. Count the patients in each age group.
select 
case
     when timestampdiff(year,date_of_birth,curdate()) <18 
  then 'under 18'
    when timestampdiff(year,date_of_birth,curdate()) between 18 and 30
    then '18-30'
      when timestampdiff(year,date_of_birth,curdate()) between 31 and 45
      then'31-45'
        when timestampdiff(year,date_of_birth,curdate()) between 46 and 60
        then '46-60'
  else 'over 60' 
  end as age_categorie,
count(*) as patient_count
from patients group by age_categorie order by min(timestampdiff(year,date_of_birth,curdate())) ;













